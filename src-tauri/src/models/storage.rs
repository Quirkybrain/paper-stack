//! Contract models for storage records and session state (contracts §3.4).

use serde::{Deserialize, Serialize};

use super::diagnostics::ErrorPayload;
use super::SourceRange;

/// Reading anchor recorded with a position (data-model §3.3; contracts §3.4).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct AnchorRecord {
    pub version_hash: String,
    pub heading_path: Vec<String>,
    pub block_fingerprint: String,
    pub offset_ratio: f64,
    pub source_range: SourceRange,
}

/// Stored reading position (contracts §3.4).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct PositionRecord {
    pub doc_id: String,
    pub anchor: AnchorRecord,
    pub updated_at_ms: i64,
}

/// `save_position` request (contracts §3.4).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct SavePositionRequest {
    pub doc_id: String,
    pub anchor: AnchorRecord,
}

/// Write-gate aware save result; suppressed writes return `saved=false`
/// without an error (data-model §6).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct SaveResult {
    pub saved: bool,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub error: Option<ErrorPayload>,
}

/// Recent-list entry; `available` is the read-time recheck result (contracts
/// §3.4).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct RecentEntry {
    pub doc_id: String,
    pub display_name: String,
    pub canonical_path: String,
    pub opened_at_ms: i64,
    pub available: bool,
}

/// One session tab; `tabId` is generated by the frontend (data-model §3.4).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct SessionTab {
    pub tab_id: String,
    pub doc_id: String,
    pub order_index: u64,
    pub is_active: bool,
}

/// `save_session` request (contracts §3.4).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct SaveSessionRequest {
    pub tabs: Vec<SessionTab>,
}

/// Stored session snapshot; `activeTabId` is explicitly nullable (contracts
/// §3.4).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct SessionSnapshot {
    pub tabs: Vec<SessionTab>,
    pub active_tab_id: Option<String>,
    pub saved_at_ms: i64,
}

/// Clearable record categories (contracts §3.4, data-model §6).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum StorageCategory {
    Recents,
    Positions,
    Session,
    Cache,
    Authorizations,
    Logs,
}

/// Per-category storage usage (contracts §3.4).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct StorageCategoryInfo {
    pub category: StorageCategory,
    pub count: u64,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub bytes: Option<u64>,
}

/// Storage overview (contracts §3.4).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct StorageOverview {
    pub categories: Vec<StorageCategoryInfo>,
    pub database_path: String,
    pub cache_dir: String,
}

/// `clear_records` request; requires explicit confirmation (R27).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ClearRecordsRequest {
    pub categories: Vec<StorageCategory>,
    pub confirm: bool,
}

/// Per-category clear result; each category reports its own outcome
/// (contracts §2.1, §3.4).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ClearResult {
    pub category: StorageCategory,
    pub cleared: u64,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub error: Option<ErrorPayload>,
}

/// `resume_recording` request; omitted categories resume all (contracts §3.4).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ResumeRecordingRequest {
    #[serde(skip_serializing_if = "Option::is_none")]
    pub categories: Option<Vec<StorageCategory>>,
}
